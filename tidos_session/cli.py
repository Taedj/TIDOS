"""tidos_session - START TIDOS mode detection and briefs.

  start [--tool T] [--model M] [--project DIR] [--json]   detect tool/model/tier, pick LEARN or GUIDE mode,
                                                           save ~/.tidos/session.json, print report + brief
  status                                                   show the current session
  tier MODEL                                               show the tier a model id maps to
  --version                                                print the TIDOS version from VERSION.md
"""
import argparse
import json
import os
import re
import sys
from datetime import datetime, timezone

from . import brief, detect, effect, memory


def _session_path():
    return os.path.join(detect.tidos_home(), "session.json")


def version():
    """Current TIDOS version: the single source is VERSION.md."""
    try:
        with open(os.path.join(detect.REPO_ROOT, "VERSION.md"), "r", encoding="utf-8") as f:
            m = re.search(r"\*\*Current Version\*\*:\s*(\S+)", f.read())
    except OSError:
        m = None
    return m.group(1) if m else "unknown"


def refresh_learning():
    """Import new sessions and regenerate playbooks so the brief uses everything learned so far."""
    try:
        from tidos_brain import claude_code, db, opencode
        from tidos_learn import distill
        conn = db.connect()
        claude_code.import_all(conn)
        opencode.import_all(conn)
        distill.distill(conn)
        conn.close()
        _spawn_summaries()
        return True
    except Exception:  # noqa: BLE001 - learning must never block START TIDOS
        return False


def _spawn_summaries():
    """Strong-model session summaries run in the background so START TIDOS stays fast."""
    import subprocess
    learn = os.path.join(detect.REPO_ROOT, "tidos_learn", "__main__.py")
    kwargs = {"stdin": subprocess.DEVNULL, "stdout": subprocess.DEVNULL, "stderr": subprocess.DEVNULL}
    if os.name == "nt":
        kwargs["creationflags"] = subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP
    else:
        kwargs["start_new_session"] = True
    subprocess.Popen([sys.executable, "-I", learn, "summarize", "--pending"], **kwargs)


def start(tool=None, model=None, project=".", env=None, learn=False):
    project = os.path.abspath(project)
    try:
        memory.migrate()  # personal memory never stays in the repository
    except OSError:
        pass
    if learn:
        refresh_learning()
    tool = detect.detect_tool(tool, env)
    model, source = detect.detect_model(tool, model, project)
    tier, pattern = detect.tier_for(model)
    session = {"tool": tool, "model": model, "model_source": source, "tier": tier, "tier_rule": pattern,
               "mode": "learn" if tier == "frontier" else "guide", "project": project,
               "started_at": datetime.now(timezone.utc).isoformat(timespec="seconds")}
    facts = detect.project_facts(project)
    text = brief.learn_brief(session, facts) if session["mode"] == "learn" else brief.guide_brief(session, facts)
    os.makedirs(detect.tidos_home(), exist_ok=True)
    with open(_session_path(), "w", encoding="utf-8") as f:
        json.dump(dict(session, facts=facts), f, indent=2)
    with open(os.path.join(detect.tidos_home(), "brief.md"), "w", encoding="utf-8") as f:
        f.write(text)
    effect.log_start(session)
    with open(os.path.join(detect.tidos_home(), "repo_path"), "w", encoding="utf-8") as f:
        f.write(detect.REPO_ROOT)  # lets the Claude Code plugin launcher find this checkout
    return session, facts, text


INSTRUCTION_FILES = {"claude-code": "CLAUDE.md", "opencode": "AGENTS.md", "codex": "AGENTS.md",
                     "gemini-cli": "GEMINI.md", "cursor": ".cursor/rules/tidos.mdc", "windsurf": ".windsurf/rules/tidos.md",
                     "cline": ".clinerules", "roo-code": ".roo/rules/tidos.md"}


def snippet(tool):
    """Instructions to paste into a tool's own instruction file (see docs/tools/)."""
    if os.name == "nt":
        cmd = 'powershell -ExecutionPolicy Bypass -File "%s" -Tool %s' % (
            os.path.join(detect.REPO_ROOT, "start_tidos.ps1"), tool)
    else:
        cmd = '"%s" --tool=%s' % (os.path.join(detect.REPO_ROOT, "scripts", "start_tidos.sh"), tool)
    return ("<!-- paste into %s -->\n## TIDOS\nWhen the user says **START TIDOS**:\n"
            "1. Run `%s` (add `-Model <your exact model id>` if you know it).\n"
            "2. Follow the brief it prints for the whole session (LEARN mode on strong models, GUIDE mode on weak ones).\n"
            "3. If it reports a TIDOS update, tell the user what it contains; install it only if they approve.\n"
            "Never ask for, repeat or store passwords or tokens in the chat.\n"
            % (INSTRUCTION_FILES.get(tool, "AGENTS.md"), cmd))


AGENTS_BEGIN = "<!-- TIDOS:BEGIN (generated by tidos_session agents-md; edits inside are replaced) -->"
AGENTS_END = "<!-- TIDOS:END -->"


def agents_md_block(project, tool="any"):
    """AGENTS.md section for any agent. Public by design: no learned playbooks, rules or notes (those stay private)."""
    facts = detect.project_facts(project)
    checks = ", ".join("`%s`" % c for c in facts["checks"]) or "ask the user how this project is checked"
    body = snippet(tool).split("\n", 1)[1]  # drop the "paste into" comment
    return "\n".join([
        AGENTS_BEGIN, body.rstrip(), "",
        "If the `tidos` MCP server is available: call `tidos_start` once, `tidos_guide` at every new request, and",
        "`tidos_verify` before saying a task is done.", "",
        "Checks for this project: %s." % checks, AGENTS_END, ""])


def write_agents_md(project, tool="any"):
    """Insert or replace the TIDOS block in <project>/AGENTS.md (other content is kept)."""
    path = os.path.join(project, "AGENTS.md")
    block = agents_md_block(project, tool)
    try:
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
    except OSError:
        text = ""
    if AGENTS_BEGIN in text and AGENTS_END in text:
        start = text.index(AGENTS_BEGIN)
        end = text.index(AGENTS_END) + len(AGENTS_END)
        text = text[:start] + block.rstrip("\n") + text[end:]
    else:
        text = (text.rstrip("\n") + "\n\n" if text.strip() else "") + block
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return path


def report(session, facts):
    return ("TIDOS session\n"
            "  tool : %(tool)s\n  model: %(model)s  (%(model_source)s)\n  tier : %(tier)s  (rule %(tier_rule)s)\n"
            "  mode : %(mode)s\n" % session
            + "  project: %s  [%s]\n" % (facts["name"], ", ".join(facts["stack"])))


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(errors="replace")
        except AttributeError:
            pass
    parser = argparse.ArgumentParser(prog="tidos_session")
    parser.add_argument("--version", action="version", version=version())
    sub =parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("start")
    p.add_argument("--tool", default="auto")
    p.add_argument("--model", default="auto")
    p.add_argument("--project", default=".")
    p.add_argument("--json", action="store_true")
    p.add_argument("--no-learn", action="store_true", help="skip refreshing the brain and playbooks")
    sub.add_parser("status")
    g = sub.add_parser("guide", help="guidance for one user request (GUIDE mode, just in time)")
    g.add_argument("request")
    g.add_argument("--project", default=".")
    rv = sub.add_parser("review", help="second opinion on the current git diff from a different model")
    rv.add_argument("--with", dest="reviewer", default="claude:sonnet")
    rv.add_argument("--project", default=".")
    rv.add_argument("--staged", action="store_true")
    sub.add_parser("effect", help="does GUIDE mode help? guided vs unguided weak-model tasks")
    am = sub.add_parser("agents-md", help="TIDOS section for a project's AGENTS.md (print, or --write)")
    am.add_argument("--project", default=".")
    am.add_argument("--tool", default="any")
    am.add_argument("--write", action="store_true")
    sn = sub.add_parser("snippet", help="START TIDOS instructions to paste into a tool's instruction file")
    sn.add_argument("--tool", default="claude-code")
    t = sub.add_parser("tier")
    t.add_argument("model")
    args = parser.parse_args(argv)

    if args.command == "start":
        session, facts, text = start(args.tool, args.model, args.project, learn=not args.no_learn)
        if args.json:
            print(json.dumps(dict(session, facts=facts, brief=text), indent=2))
        else:
            print(report(session, facts))
            print(text)
        return 0
    if args.command == "review":
        from . import review
        text, error = review.second_opinion(os.path.abspath(args.project), args.reviewer, args.staged)
        try:
            with open(_session_path(), "r", encoding="utf-8") as f:
                warning = review.same_family_warning(args.reviewer, json.load(f).get("model"))
        except (OSError, ValueError):
            warning = None
        if warning:
            print(warning + "\n")
        print(("Second opinion (%s) - reviewer input only, you decide:\n\n%s" % (args.reviewer, text)) if text
              else "No review: %s" % error)
        return 0 if text else 1
    if args.command == "effect":
        from tidos_brain import db
        conn = db.connect()
        for row in effect.guidance_effect(conn):
            for side in ("guided", "unguided"):
                st = row[side]
                print("%-46s %-9s tasks %4d  checks passed %s  corrected %s" % (
                    row["model"][:46], side, st["tasks"],
                    "%3s%%" % st["pass_rate"] if st["pass_rate"] is not None else "  -",
                    "%3s%%" % st["correction_rate"] if st["correction_rate"] is not None else "  -"))
        conn.close()
        return 0
    if args.command == "agents-md":
        project = os.path.abspath(args.project)
        if args.write:
            print("Updated %s" % write_agents_md(project, args.tool))
        else:
            print(agents_md_block(project, args.tool))
        return 0
    if args.command == "snippet":
        print(snippet(args.tool))
        return 0
    if args.command == "guide":
        from . import guide
        print(guide.guidance(args.request, args.project)[1])
        return 0
    if args.command == "status":
        try:
            with open(_session_path(), "r", encoding="utf-8") as f:
                print(json.dumps(json.load(f), indent=2))
        except OSError:
            print("No TIDOS session yet. Run START TIDOS.")
        return 0
    tier, pattern = detect.tier_for(args.model)
    print("%s -> %s  (rule %s, mode %s)" % (args.model, tier, pattern, "learn" if tier == "frontier" else "guide"))
    return 0
