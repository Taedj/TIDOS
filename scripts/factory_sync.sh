#!/usr/bin/env bash
# ============================================================================
# TIDOS Persona Factory Sync (Linux/macOS Bash)
# ============================================================================
# Stages ONLY factory-generated paths (new persona spec + registry + evolution)
# on a review branch and opens a pull request. Never pushes to main.
#
# Usage:
#   ./scripts/factory_sync.ps1                      # detect + commit + push
#   ./scripts/factory_sync.ps1 -Persona <NAME>      # explicitly name path
#   ./scripts/factory_sync.ps1 -Message "<msg>"     # custom commit message
#   ./scripts/factory_sync.ps1 -DryRun              # show what would be staged
#
# Exit: 0 = pushed, 1 = nothing to push / blocked, 2 = error
# ============================================================================

PY="$(command -v python3 || command -v python)"   # Git Bash on Windows has no python3
REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO" || { echo "ERROR: Not a git repo: $REPO" >&2; exit 2; }

# Kill switch (~/.tidos/control.json, /TIDOSZIT)
rc=0; "$PY" -I "$REPO/tidos_brain/control.py" get factory_sync >/dev/null 2>&1 || rc=$?
if [ "$rc" -eq 1 ]; then echo "Factory sync is switched OFF in the TIDOS control center (/TIDOSZIT)." >&2; exit 1; fi

PERSONA=""
MESSAGE=""
DRYRUN=0

while [ $# -gt 0 ]; do
  case "$1" in
    -Persona) PERSONA="$2"; shift 2 ;;
    -Message) MESSAGE="$2"; shift 2 ;;
    -DryRun)  DRYRUN=1; shift ;;
    *) shift ;;
  esac
done

# --- detect untracked persona file if not given --------------------------------
if [ -z "$PERSONA" ]; then
  PERSONA=$(git status --porcelain -- personas | grep -E '^\?\? personas/tidos[^ ]+\.md$' | head -n1 | cut -c4-)
fi
[ -n "$PERSONA" ] || { echo "ERROR: No new persona detected to sync. Expected new personas/tidos*.md." >&2; exit 1; }

# --- guard: only factory paths -----------------------------------------------
FACTORY_PATHS="$PERSONA
personas/registry.md
evolution/SUGGESTIONS.md"
UNRELATED=$(git status --porcelain | awk '{print $2}' | grep -vFf <(echo "$FACTORY_PATHS") | head -n5)
if [ -n "$UNRELATED" ]; then
  echo "BLOCKED: unrelated changes would be included:" >&2
  echo "$UNRELATED" >&2
  echo "Stash/commit unrelated changes first; factory_sync commits ONLY the persona trio." >&2
  exit 1
fi

# --- privacy firewall -----------------------------------------------------------
for f in "$PERSONA" personas/registry.md evolution/SUGGESTIONS.md; do
  "$PY" "$REPO/scripts/sanitizer.py" --check "$f" || { echo "ERROR: Privacy Firewall REJECTED $f. Aborting sync." >&2; exit 2; }
done

# --- message ------------------------------------------------------------------
NAME=$(basename "$PERSONA" .md)
[ -z "$MESSAGE" ] && MESSAGE="feat(persona-factory): $NAME persona auto-generated (discovered domain/stack)"

# --- stage & commit -----------------------------------------------------------
git add "$PERSONA" personas/registry.md evolution/SUGGESTIONS.md
echo "Staging: $PERSONA + personas/registry.md + evolution/SUGGESTIONS.md"
echo "Message: $MESSAGE"
if [ "$DRYRUN" = "1" ]; then echo "[dry-run] push skipped. Staged:"; git diff --cached --name-status; exit 0; fi

# --- commit on a review branch and open a pull request (never push to main) ----
BASE=$(git branch --show-current)
BRANCH="persona/$NAME-$(date +%Y%m%d-%H%M%S)"
git checkout -q -b "$BRANCH"
git commit -m "$MESSAGE" >/dev/null 2>&1
if ! git push -u origin "$BRANCH" 2>&1; then
  git checkout -q "$BASE"
  echo "ERROR: push of branch $BRANCH failed. The commit is kept on local branch $BRANCH." >&2
  exit 1
fi
git checkout -q "$BASE"
if command -v gh >/dev/null; then
  gh pr create --base main --head "$BRANCH" --title "$MESSAGE"     --body "Generated by the TIDOS persona factory. Audited by the privacy firewall. Review before merging."
else
  echo "Open the pull request: https://github.com/Taedj/TIDOS/compare/main...$BRANCH"
fi
echo "Persona proposed on branch $BRANCH. It reaches users only after a human merges it."
exit 0
