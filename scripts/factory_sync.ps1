# ============================================================================
# TIDOS Persona Factory Sync (Windows PowerShell)
# ============================================================================
# Stages ONLY factory-generated paths (new persona spec + registry + evolution)
# on a review branch and opens a pull request. Never pushes to main.
#
# Usage:
#   .\scripts\factory_sync.ps1                        # commit + push new persona
#   .\scripts\factory_sync.ps1 -Persona <NAME>        # name (default: detected new line)
#   .\scripts\factory_sync.ps1 -Message "<msg>"       # custom commit message
#   .\scripts\factory_sync.ps1 -DryRun                # show what would be staged
#
# Exit: 0 = pushed, 1 = nothing to push / blocked, 2 = error
# ============================================================================

param(
    [string]$Persona,
    [string]$Message,
    [switch]$DryRun
)

$ErrorActionPreference = "Stop"
function Fail($msg, $code) { Write-Error $msg; exit $code }

$repo = (Resolve-Path (Join-Path $PSScriptRoot ".."))
Set-Location $repo

if (-not (Test-Path ".git")) { Fail "Not a git repo: $repo" 2 }

# Kill switch (~/.tidos/control.json, /TIDOSZIT)
$ctl = Join-Path $repo "tidos_brain/control.py"
if (Test-Path $ctl) {
    & python -I $ctl get factory_sync | Out-Null
    if ($LASTEXITCODE -eq 1) { Fail "Factory sync is switched OFF in the TIDOS control center (/TIDOSZIT)." 1 }
}

# --- Detect the new persona file if not supplied -------------------------------
function Find-NewPersona {
    $untracked = git status --porcelain -- personas
    $cand = $untracked | Select-String '^\?\?\s+personas/tidos.+\.md$'
    if ($cand) { return ($cand[0].Line -replace '^\?\?\s+', '').Trim() }
    return $null
}

if (-not $Persona) { $Persona = Find-NewPersona }
if (-not $Persona) { Fail "No new persona detected to sync. Expected new personas/tidos*.md." 1 }

# --- Guard: only factory paths go in -------------------------------------------
$factoryPaths = @($Persona, "personas/registry.md", "evolution/SUGGESTIONS.md")
$allChanges = git status --porcelain
$blocked = $allChanges | Where-Object { $_ -match '^\?\?' -or $_ -match '^ M ' } |
    ForEach-Object { ($_ -replace '^(..) ', '') } |
    Where-Object { $_ -notin $factoryPaths }

if ($blocked.Count -gt 0) {
    Write-Host "BLOCKED: unrelated changes would be included:"
    $blocked | ForEach-Object { Write-Host "  $_" }
    Fail "Stash/commit unrelated changes first; factory_sync commits ONLY the persona trio." 1
}

# --- Privacy & Sanitization Firewall Audit -----------------------------------
Write-Host "Running Privacy Firewall audit on $Persona..."
foreach ($f in @($Persona, "personas/registry.md", "evolution/SUGGESTIONS.md")) {
    & python (Join-Path $repo "scripts/sanitizer.py") --check $f
    if ($LASTEXITCODE -ne 0) { break }
}
if ($LASTEXITCODE -ne 0) {
    Fail "Privacy Firewall REJECTED persona: Secrets or prohibited patterns found in $Persona. Aborting sync." 2
}
Write-Host "[OK] Privacy Firewall PASSED: Zero secrets, PII, or forbidden code found."

# --- Message ---------------------------------------------------------------
$name = (Split-Path $Persona -Leaf) -replace '\.md$', ''
if (-not $Message) { $Message = "feat(persona-factory): $name persona auto-generated (discovered domain/stack)" }

# --- Stage & show --------------------------------------------------------------
git add $Persona "personas/registry.md" "evolution/SUGGESTIONS.md"
Write-Host "Staging: $Persona + personas/registry.md + evolution/SUGGESTIONS.md"
Write-Host "Message: $Message"
if ($DryRun) { Write-Host "[dry-run] push skipped. Staged files:"; git diff --cached --name-status; exit 0 }

# --- Commit on a review branch and open a pull request (never push to main) ----
$base = (git branch --show-current).Trim()
$branch = "persona/$name-" + (Get-Date -Format "yyyyMMdd-HHmmss")
git checkout -q -b $branch
git commit -m $Message | Out-Null
# no 2>&1 here: with ErrorActionPreference=Stop, PowerShell 5.1 turns git's progress output into a fatal error
& git push -u origin $branch
$pushed = ($LASTEXITCODE -eq 0)
git checkout -q $base
if (-not $pushed) { Fail "Push of branch $branch failed (see above). The commit is kept on local branch $branch." 1 }
if (Get-Command gh -ErrorAction SilentlyContinue) {
    gh pr create --base main --head $branch --title $Message --body "Generated by the TIDOS persona factory. Audited by the privacy firewall. Review before merging."
} else {
    Write-Host "Open the pull request: https://github.com/Taedj/TIDOS/compare/main...$branch" -ForegroundColor Cyan
}
Write-Host "Persona proposed on branch $branch. It reaches users only after a human merges it." -ForegroundColor Green
exit 0
