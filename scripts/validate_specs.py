"""TIDOS spec validator (CI): structure checks that prose alone cannot guarantee.

  - personas: every personas/tidos*.md has a title and is registered in personas/registry.md;
    generated personas follow the factory schema (NEGATIVE CONSTRAINTS + Routing Signals mandatory)
  - registry links point to existing persona files
  - VERSION.md and config/framework.md agree on the version
  - config/models.json is valid and only uses known tiers
  - every evals/dungeons/*/*/task.json is well-formed
  - repo-relative Markdown links point to existing files

Usage: python scripts/validate_specs.py      (exit 1 on any error)
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GENERATED_SECTIONS = ["PERSONA IDENTITY", "CORE PHILOSOPHY", "NEGATIVE CONSTRAINTS", "DOMAIN SPECIALIZATION",
                      "INPUT & AUDIT", "OUTPUT FORMAT", "GOVERNED WORKFLOW", "INVOCATION PROTOCOL", "Routing Signals"]
LINK = re.compile(r"\]\(([^)\s]+)\)")
SKIP_DIRS = {".git", "node_modules", "__pycache__", "evals", "browser_relay"}


def read(rel):
    with open(os.path.join(ROOT, rel), "r", encoding="utf-8") as f:
        return f.read()


def check_personas(errors):
    registry = read("personas/registry.md")
    for path in sorted(glob.glob(os.path.join(ROOT, "personas", "tidos*.md"))):
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        text = read(rel)
        if not re.match(r"\s*# \S", text):
            errors.append("%s: missing '# Title' first line" % rel)
        if os.path.basename(rel) not in registry:
            errors.append("%s: not registered in personas/registry.md" % rel)
        if "Auto-generated by Persona Factory" in text:
            for section in GENERATED_SECTIONS:
                if section.lower() not in text.lower():
                    errors.append("%s: generated persona missing section '%s'" % (rel, section))
    for target in re.findall(r"\(([^)]*personas/tidos[^)#]*\.md)", registry):
        name = target.split("/")[-1]
        if not os.path.exists(os.path.join(ROOT, "personas", name)):
            errors.append("personas/registry.md: links missing persona %s" % name)


def check_versions(errors):
    m = re.search(r"\*\*Current Version\*\*:\s*(\S+)", read("VERSION.md"))
    c = re.search(r"current:\s*(\S+)", read("config/framework.md"))
    if not m or not c:
        errors.append("VERSION.md or config/framework.md: version not found")
    elif m.group(1) != c.group(1):
        errors.append("version mismatch: VERSION.md %s vs config/framework.md %s" % (m.group(1), c.group(1)))


def check_models(errors):
    try:
        rules = json.loads(read("config/models.json"))["rules"]
    except (ValueError, KeyError) as e:
        errors.append("config/models.json: %s" % e)
        return
    for rule in rules:
        if len(rule) != 2 or rule[1] not in ("frontier", "medium", "weak"):
            errors.append("config/models.json: bad rule %r" % (rule,))
    if not rules or rules[-1][0] != "*":
        errors.append("config/models.json: last rule must be the '*' fallback")


def check_dungeons(errors):
    for path in glob.glob(os.path.join(ROOT, "evals", "dungeons", "*", "*", "task.json")):
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        try:
            meta = json.loads(read(rel))
        except ValueError as e:
            errors.append("%s: invalid JSON (%s)" % (rel, e))
            continue
        for key in ("suite", "name", "difficulty", "prompt", "verify"):
            if key not in meta:
                errors.append("%s: missing %s" % (rel, key))
        if meta.get("difficulty") not in list("EDCBAS"):
            errors.append("%s: difficulty must be one of E D C B A S" % rel)
        base = os.path.dirname(path)
        for part in ("fixture", "hidden", "solution"):
            if not os.path.isdir(os.path.join(base, part)):
                errors.append("%s: missing %s/" % (rel, part))


def check_skills(errors):
    for path in glob.glob(os.path.join(ROOT, ".claude", "skills", "*", "SKILL.md")):
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        text = read(rel)
        name = re.search(r"^name:\s*(\S+)", text, re.M)
        desc = re.search(r"^description:\s*(.{40,})$", text, re.M)
        folder = os.path.basename(os.path.dirname(path))
        if not text.startswith("---") or not name or name.group(1) != folder:
            errors.append("%s: front matter 'name' must equal the folder name" % rel)
        if not desc:
            errors.append("%s: needs a 'description' that says what it does and when to use it" % rel)


def check_links(errors):
    for dirpath, dirnames, files in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in files:
            if not name.endswith(".md"):
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, ROOT).replace("\\", "/")
            with open(path, "r", encoding="utf-8", errors="replace") as f:
                text = re.sub(r"```.*?```", "", f.read(), flags=re.S)  # ignore code blocks
            for target in LINK.findall(text):
                if re.match(r"^[a-z]+:", target) or target.startswith("#") or "<" in target:
                    continue
                clean = target.split("#")[0]
                if not clean:
                    continue
                full = os.path.join(ROOT, clean.lstrip("/")) if clean.startswith("/") else os.path.join(dirpath, clean)
                if not os.path.exists(full):
                    errors.append("%s: broken link -> %s" % (rel, target))


def main():
    errors = []
    for check in (check_personas, check_versions, check_models, check_dungeons, check_skills, check_links):
        check(errors)
    for e in errors:
        print("ERROR " + e)
    print("%d error(s)" % len(errors))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
